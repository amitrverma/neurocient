import type { EvidenceTarget, ScanOption, ScanScenario, TriggerId } from "./types";

const option = (scenario: TriggerId, target: EvidenceTarget, text: string): ScanOption => ({
  id: `${scenario}-${target}`,
  text,
  mapping: { primary: target, weight: 1 },
});

